import { writeFileSync } from 'node:fs';
import path from 'node:path';

import ts from 'typescript';

const config = ts.readConfigFile('tsconfig.json', ts.sys.readFile);

const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, process.cwd());

const program = ts.createProgram(parsed.fileNames, parsed.options);

const checker = program.getTypeChecker();

const source = program.getSourceFile(path.resolve('src/ports/inbound/cms/cms-api.port.ts'));

const declaration = source.statements.find((node) => ts.isTypeAliasDeclaration(node) && node.name.text === 'CmsApi');

const root = checker.getTypeAtLocation(declaration);

const definitions = new Map();

const names = new Map();

let sequence = 0;

function identifier(value) {
  return value.replace(/[^A-Za-z0-9]/g, '').slice(0, 48);
}

function renderProperty(type, hint, optional) {
  if (optional && type.isUnion()) {
    return type.types.filter((item) => !(item.flags & ts.TypeFlags.Undefined))
      .map((item) => render(item, hint)).join('\n    | ');
  }

  return render(type, hint);
}

function render(type, hint = 'Value') {
  if (type.flags & ts.TypeFlags.StringLiteral) {
    return JSON.stringify(type.value);
  }
  if (type.flags & ts.TypeFlags.NumberLiteral) {
    return String(type.value);
  }
  if (type.flags & ts.TypeFlags.BooleanLiteral) {
    return type.intrinsicName;
  }
  if (type.flags & ts.TypeFlags.String) {
    return 'string';
  }
  if (type.flags & ts.TypeFlags.Number) {
    return 'number';
  }
  if (type.flags & ts.TypeFlags.Boolean) {
    return 'boolean';
  }
  if (type.flags & ts.TypeFlags.Null) {
    return 'null';
  }
  if (type.flags & ts.TypeFlags.Undefined) {
    return 'undefined';
  }
  if (type.flags & ts.TypeFlags.Void) {
    return 'void';
  }
  if (type.flags & ts.TypeFlags.Never) {
    return 'never';
  }
  if (type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) {
    return 'unknown';
  }
  if (names.has(type.id)) {
    return names.get(type.id);
  }
  if (type.isUnion()) {
    const name = 'TCms' + identifier(hint) + (++sequence);

    names.set(type.id, name);
    definitions.set(name, '');
    definitions.set(name, 'export type ' + name + ' = '
      + type.types.map((item) => render(item, hint)).join('\n  | ') + ';');

    return name;
  }

  const calls = type.getCallSignatures();

  if (calls.length) {
    const signature = calls[0];
    const args = signature.parameters.map((parameter, index) => {
      const node = parameter.valueDeclaration ?? declaration;
      const optional = !!node.questionToken || !!node.initializer;

      return parameter.getName() + (optional ? '?' : '') + ': '
        + render(checker.getTypeOfSymbolAtLocation(parameter, node), hint + 'Input' + index);
    });
    const returned = checker.getReturnTypeOfSignature(signature);
    const awaited = checker.getAwaitedType(returned);

    return '(\n    ' + args.join(',\n    ') + '\n  ) => Promise<' + render(awaited, hint + 'Result') + '>';
  }
  if (checker.isArrayType(type) || checker.isTupleType(type)) {
    const element = checker.getIndexTypeOfType(type, ts.IndexKind.Number);

    return 'readonly (' + render(element, hint + 'Item') + ')[]';
  }
  if (names.has(type.id)) {
    return names.get(type.id);
  }

  const name = 'ICms' + identifier(hint) + (++sequence);

  names.set(type.id, name);
  definitions.set(name, '');
  const fields = checker.getPropertiesOfType(type).map((property) => {
    const node = property.valueDeclaration ?? property.declarations?.[0] ?? declaration;

    return '  readonly ' + JSON.stringify(property.getName()) + ((property.flags & ts.SymbolFlags.Optional) ? '?' : '')
      + ': ' + renderProperty(checker.getTypeOfSymbolAtLocation(property, node),
      hint + identifier(property.getName()), !!(property.flags & ts.SymbolFlags.Optional)) + ';';
  });

  for (const index of checker.getIndexInfosOfType(type)) {
    fields.push('  readonly [key: ' + render(index.keyType) + ']: ' + render(index.type, hint + 'Value') + ';');
  }
  definitions.set(name, fields.length ? 'export interface ' + name + ' {\n' + fields.join('\n') + '\n}'
    : 'export type ' + name + ' = Record<never, never>;');

  return name;
}

const properties = checker.getPropertiesOfType(root).filter((property) => property.getName() !== 'extensions');

const fields = properties.map((property) => '  readonly ' + property.getName() + ': '
  + render(checker.getTypeOfSymbolAtLocation(property, declaration), property.getName()) + ';');

const output = '// Generated by scripts/generate-cms-contracts.mjs from the approved server facade.\n'
  + '// Public data contracts only: no core imports, entities, persistence or framework types.\n'
  + "import type { CmsExtensions } from './cms-extensions.js';\n\n"
  + 'export interface ICmsCoreApi {\n' + fields.join('\n') + '\n}\n\n'
  + 'export type ICmsApi = ICmsCoreApi & { readonly extensions: CmsExtensions };\n\n'
  + [...definitions.values()].join('\n\n') + '\n';

writeFileSync(process.argv[2] ?? '.tmp/cms-contracts.ts', output);
